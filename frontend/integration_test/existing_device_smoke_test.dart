import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:integration_test/integration_test.dart';
import 'package:frontend/modules/devices/services/device_key_store.dart';
import 'package:frontend/modules/devices/services/device_verification_service.dart';
import 'package:frontend/services/api_client.dart';

/// Opt-in, real-phone smoke test: reads/signs with the EXISTING key only.
/// Creates its own login and proof audit, then logs out that login. No enrollment.
void main() {
  IntegrationTestWidgetsFlutterBinding.ensureInitialized();
  const student = String.fromEnvironment(
    'DEVICE_TEST_STUDENT',
    defaultValue: 'DEMO001',
  );
  const password = String.fromEnvironment('DEVICE_TEST_PASSWORD');
  const expectedFingerprint = String.fromEnvironment('DEVICE_TEST_FINGERPRINT');
  testWidgets('Existing registered Keystore key still passes Stage A', (
    tester,
  ) async {
    await tester.pumpWidget(
      const MaterialApp(
        home: Scaffold(body: Text('Existing-key verification test')),
      ),
    );
    await tester.runAsync(() async {
      const keys = DeviceKeyStore();
      final before = await keys.getPublicKey(student);
      expect(
        before,
        isNotNull,
        reason: 'No key is generated by this smoke test.',
      );
      if (expectedFingerprint.isNotEmpty) {
        expect(before!['public_key_fingerprint'], expectedFingerprint);
      }
      final client = ApiClient();
      try {
        await client.login(student, password);
        final proof = await DeviceVerificationService(
          client: client,
          keys: keys,
        ).verify();
        expect(proof.deviceId, isNotEmpty);
        final listing = await client.get('/api/v1/devices') as Map;
        final current = (listing['devices'] as List).cast<Map>().singleWhere(
          (row) => row['device_id'] == proof.deviceId,
        );
        expect(
          current['public_key_fingerprint'],
          before!['public_key_fingerprint'],
        );
        expect(current['status'], 'ACTIVE');
        final after = await keys.getPublicKey(student);
        expect(
          after!['public_key_fingerprint'],
          before['public_key_fingerprint'],
        );
      } finally {
        if (client.authenticated.value) await client.logout();
      }
    });
  }, skip: password.isEmpty);
}
